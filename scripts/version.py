# PlatformIO pre-build script: stamp the firmware with its git identity.
#
# Writes src/fw_version.h (gitignored) with FW_VERSION ("r<commit count>-<short
# sha>[-dirty]", for humans) and FW_GIT_SHA (full sha, "-dirty" appended for
# uncommitted trees, so a dirty build never matches a published one). The
# updater compares FW_GIT_SHA with the release channel's manifest. The header
# is rewritten only when its content changes, so unrelated rebuilds stay
# incremental.
import os
import subprocess

Import("env")  # noqa: F821 (provided by SCons)

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821


def git(*args):
    try:
        out = subprocess.check_output(
            # safe.directory: the Docker build runs as a different uid than the
            # checkout's owner, which git otherwise refuses.
            ["git", "-c", "safe.directory=*", *args],
            cwd=project_dir, stderr=subprocess.DEVNULL)
        return out.decode().strip()
    except Exception:
        return ""


sha = git("rev-parse", "HEAD") or "unknown"
count = git("rev-list", "--count", "HEAD") or "0"
# core.fileMode=false: CI chmods the checkout so the build container can write
# it; mode bits alone must not make a build "dirty".
dirty = bool(git("-c", "core.fileMode=false", "status", "--porcelain", "--untracked-files=no"))
suffix = "-dirty" if dirty else ""
version = "r%s-%s%s" % (count, sha[:7], suffix)

header = (
    "// Generated by scripts/version.py - do not edit, not committed.\n"
    "#pragma once\n"
    '#define FW_VERSION "%s"\n'
    '#define FW_GIT_SHA "%s%s"\n' % (version, sha, suffix)
)

path = os.path.join(project_dir, "src", "fw_version.h")
try:
    with open(path) as f:
        current = f.read()
except OSError:
    current = ""
if current != header:
    with open(path, "w") as f:
        f.write(header)
print("Firmware version: %s" % version)
